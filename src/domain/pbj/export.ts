/**
 * PBJ export service boundary.
 *
 * Production intent: an export service generates the XML file defined by the current CMS
 * PBJ data submission specifications, validates it against the official XSD, and hands
 * the file to the facility for upload to iQIES (or submits via a future integration).
 *
 * This prototype implementation produces an ILLUSTRATIVE XML document. Element names
 * approximate the published PBJ structure but the file has NOT been validated against the
 * CMS schema and must not be submitted.
 */
import type { Employee, Facility } from '../types';
import type { FiscalQuarter } from '../time';
import type { PbjDailyRow, PbjResult } from './engine';
import { RULE_BY_ID } from './rules';

export const DEMO_EXPORT_BANNER = 'Demo — not validated for CMS submission';

export interface PbjExportService {
  /** Build an export payload from rows that are ready. */
  buildExport(input: { facility: Facility; quarter: FiscalQuarter; result: PbjResult; employees: Employee[]; generatedAt: string }): {
    fileName: string;
    mimeType: string;
    content: string;
    workerCount: number;
    dayRowCount: number;
    totalHours: number;
  };
  /** Schema validation is not available in the prototype. */
  validateAgainstSchema?: (content: string) => Promise<{ valid: boolean; messages: string[] }>;
  /** Direct submission to iQIES is a planned integration. */
  submit?: never;
}

function esc(s: string): string {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

export const demoXmlExportService: PbjExportService = {
  buildExport({ facility, quarter, result, employees, generatedAt }) {
    const ready = result.rows.filter((r) => r.status === 'ready' && r.pbjJobTitleCode && r.eligibleHours > 0);
    const byWorker = new Map<string, PbjDailyRow[]>();
    for (const r of ready) byWorker.set(r.pbjEmployeeId, [...(byWorker.get(r.pbjEmployeeId) ?? []), r]);
    const empByPbj = new Map(employees.map((e) => [e.pbjEmployeeId, e]));
    const lines: string[] = [];
    lines.push('<?xml version="1.0" encoding="UTF-8"?>');
    lines.push(`<!-- ${DEMO_EXPORT_BANNER}. Generated by the Poise prototype on ${generatedAt}. -->`);
    lines.push('<!-- Fictional data. Element structure is illustrative and has not been validated against the official CMS PBJ XSD. -->');
    lines.push('<nursingHomeData>');
    lines.push('  <header fileSpecVersion="DEMO">');
    lines.push(`    <facilityId>${esc(facility.pbjFacilityId || 'MISSING')}</facilityId>`);
    lines.push(`    <stateCode>${esc(facility.state)}</stateCode>`);
    lines.push(`    <reportQuarter>${quarter.quarter}</reportQuarter>`);
    lines.push(`    <federalFiscalYear>${quarter.fiscalYear}</federalFiscalYear>`);
    lines.push('    <softwareVendorName>Poise Prototype (demo)</softwareVendorName>');
    lines.push('  </header>');
    lines.push('  <employees>');
    for (const pbjId of [...byWorker.keys()].sort()) {
      const e = empByPbj.get(pbjId);
      lines.push('    <employee>');
      lines.push(`      <employeeId>${esc(pbjId)}</employeeId>`);
      if (e?.hireDate) lines.push(`      <hireDate>${e.hireDate}</hireDate>`);
      if (e?.separationDate) lines.push(`      <terminationDate>${e.separationDate}</terminationDate>`);
      lines.push('    </employee>');
    }
    lines.push('  </employees>');
    lines.push('  <staffingHours processType="merge">');
    let total = 0;
    for (const [pbjId, rows] of [...byWorker.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
      lines.push('    <staffHours>');
      lines.push(`      <employeeId>${esc(pbjId)}</employeeId>`);
      lines.push('      <workDays>');
      const byDate = new Map<string, PbjDailyRow[]>();
      for (const r of rows) byDate.set(r.date, [...(byDate.get(r.date) ?? []), r]);
      for (const [date, dr] of [...byDate.entries()].sort()) {
        lines.push('        <workDay>');
        lines.push(`          <date>${date}</date>`);
        lines.push('          <hourEntries>');
        const grouped = new Map<string, number>();
        for (const r of dr) {
          const k = `${r.pbjJobTitleCode}|${r.payTypeCode}`;
          grouped.set(k, (grouped.get(k) ?? 0) + r.eligibleHours);
        }
        for (const [k, hours] of grouped) {
          const [job, pay] = k.split('|');
          total += hours;
          lines.push(`            <hourEntry><hours>${hours.toFixed(2)}</hours><jobTitleCode>${job}</jobTitleCode><payTypeCode>${pay}</payTypeCode></hourEntry>`);
        }
        lines.push('          </hourEntries>');
        lines.push('        </workDay>');
      }
      lines.push('      </workDays>');
      lines.push('    </staffHours>');
    }
    lines.push('  </staffingHours>');
    lines.push('</nursingHomeData>');
    return {
      fileName: `poise-demo-pbj_${facility.shortName.replace(/\s+/g, '-').toLowerCase()}_${quarter.id}_NOT-FOR-SUBMISSION.xml`,
      mimeType: 'application/xml',
      content: lines.join('\n'),
      workerCount: byWorker.size,
      dayRowCount: ready.length,
      totalHours: Math.round(total * 100) / 100,
    };
  },
};

