export function toCsv(rows: (string | number | null | undefined)[][]): string {
  return rows
    .map((r) =>
      r
        .map((v) => {
          const s = v === null || v === undefined ? '' : String(v);
          return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
        })
        .join(','),
    )
    .join('\n');
}

export function dailyRowsCsv(rows: PbjDailyRow[], facility: Facility): string {
  return toCsv([
    ['worker_id', 'worker_name', 'date', 'facility', 'source_job', 'cms_job_code', 'cms_job_title', 'worker_type', 'pay_type_code', 'raw_hours', 'meal_adjustment_hours', 'eligible_hours', 'source_record', 'source', 'review_status', 'status_reason'],
    ...rows.map((r) => [
      r.pbjEmployeeId,
      r.workerName,
      r.date,
      facility.name,
      r.sourceJobCode,
      r.pbjJobTitleCode,
      r.pbjJobTitle,
      r.workerType,
      r.payTypeCode,
      (r.rawMinutes / 60).toFixed(2),
      (r.mealAdjustmentMinutes / 60).toFixed(2),
      r.eligibleHours.toFixed(2),
      r.timecardId,
      r.source,
      r.status,
      r.statusReason,
    ]),
  ]);
}

