  const issueRows = result.issues
    .map(
      (i) =>
        `<tr><td>${i.severity}</td><td>${i.ruleId}</td><td>${esc(i.title)}</td><td>${esc(i.detail)}</td><td>${i.resolution ? esc(`${i.resolution.decision} — ${i.resolution.by}: ${i.resolution.note}`) : i.severity === 'indicator' ? 'Monitoring only' : 'Open'}</td></tr>`,
    )
    .join('');
